ROWS = 8


def layout(text):
    """Yield (x, row, run_length) for every horizontal run of lit pixels."""
    x = 0
    for ch in text:
        glyph = FONT[ch]
        width = len(glyph[0])
        for row, bits in enumerate(glyph):
            col = 0
            while col < width:
                if bits[col] == "#":
                    start = col
                    while col < width and bits[col] == "#":
                        col += 1
                    yield x + start, row, col - start
                else:
                    col += 1
        x += width + 1  # 1px gap between glyphs, like the game
    return


def text_width(text):
    return sum(len(FONT[c][0]) + 1 for c in text) - 1


def svg_for(text, scale, fill, shadow, bg, pad_x=3, pad_y=2):
    w = text_width(text) + pad_x * 2
    h = ROWS + pad_y * 2
    path = "".join(
        f"M{x + pad_x} {row + pad_y}h{run}v1h-{run}z" for x, row, run in layout(text)
    )
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{w * scale}" height="{h * scale}" '
        f'viewBox="0 0 {w} {h}" role="img" aria-label="{text}">'
        f"<title>{text}</title>"
        f'<rect width="{w}" height="{h}" fill="{bg}"/>'
        f'<g shape-rendering="crispEdges">'
        f'<path d="{path}" fill="{shadow}" transform="translate(1 1)"/>'
        f'<path d="{path}" fill="{fill}"/>'
        f"</g></svg>\n"
    )


def png_preview(text, scale, fill, shadow, bg, page_bg, out, pad_x=3, pad_y=2):
    """Same pixels rasterised with Pillow, dropped on a page background, for checking."""
    from PIL import Image, ImageDraw

    w = text_width(text) + pad_x * 2
    h = ROWS + pad_y * 2
    margin = 24
    im = Image.new("RGB", (w * scale + margin * 2, h * scale + margin * 2), page_bg)
    d = ImageDraw.Draw(im)
    ox, oy = margin, margin
    d.rectangle([ox, oy, ox + w * scale - 1, oy + h * scale - 1], fill=bg)
    for dx, dy, colour in ((1, 1, shadow), (0, 0, fill)):
        for x, row, run in layout(text):
            px = ox + (x + pad_x + dx) * scale
            py = oy + (row + pad_y + dy) * scale
            d.rectangle([px, py, px + run * scale - 1, py + scale - 1], fill=colour)
    im.save(out)


YELLOW, YELLOW_SHADOW = "#FFFF55", "#3F3F15"  # the game's join/leave message colours
